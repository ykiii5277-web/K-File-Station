def table(headers, rows):
    return ('<table cellspacing="0" cellpadding="9" width="100%"><tr>'
            + ''.join('<th align="left">'+html.escape(value)+'</th>' for value in headers)
            + '</tr>'+''.join('<tr>'+''.join('<td>'+html.escape(str(value))+'</td>' for value in row)+'</tr>' for row in rows)
            + '</table>')


def conversion_table(sources=None):
    sources = converter.GRAPH if sources is None else sources
    return table(('输入格式', '可直接转换为'), [
        (source.upper(), '、'.join(target.upper() for target in converter.GRAPH[source]))
        for source in sources if converter.GRAPH.get(source)
    ])


